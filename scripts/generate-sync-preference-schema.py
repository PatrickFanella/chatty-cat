#!/usr/bin/env python3
"""Generate server preference-field allowlists from the portable TS interfaces."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
models={'displayFields':('display.ts','DisplayOptions'),'presentationFields':('presentation.ts','PresentationOptions'),'pickerFields':('picker-model.ts','PickerOptions')}
lines=['// Code generated by scripts/generate-sync-preference-schema.py; DO NOT EDIT.','package devicesync','']
for name,(path,model) in models.items():
 source=(root/'web/src'/path).read_text();match=re.search(r'export interface '+model+r'\s*\{([^{}]+)\}',source)
 if not match:raise ValueError('Expected scalar preference interface: '+model)
 fields=re.findall(r'(\w+)\??\s*:\s*([^;]+);?',match[1])
 keys=[]
 for key,value in fields:
  if not re.fullmatch(r'(?:string|number|boolean|Source\[\]|(?:\s*\|?\s*\x27[^\x27]+\x27)+)',value.strip()):raise ValueError('Unexpected preference type: '+value)
  if re.search(r'token|secret|password|whisper|journal|draft|alias',key,re.I):raise ValueError('Private preference must not be portable: '+key)
  keys.append(key)
 lines.append('const '+name+' = "'+' '.join(keys)+'"')
actions=re.findall(r"id:'([^']+)'",(root/'web/src/hotkeys.ts').read_text().split('] as const')[0]);lines.append('const hotkeyActions = \"'+' '.join(actions)+'\"')
(root/'internal/devicesync/schema_generated.go').write_text('\n'.join(lines)+'\n')
