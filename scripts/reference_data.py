"""Emit immutable reference JSON and its small runtime descriptor."""
import hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def emit(kind, value):
    raw = (json.dumps(value, ensure_ascii=False, separators=(',', ':')) + '\n').encode()
    name = kind + '-' + hashlib.sha256(raw).hexdigest()[:16] + '.json'
    target = ROOT / 'web/public/data'
    target.mkdir(exist_ok=True)
    for old in target.glob(kind + '-*.json'):
        if old.name != name: old.unlink()
    (target / name).write_bytes(raw)
    constant = kind.upper().replace('-', '_') + '_URL'
    (ROOT / ('web/src/' + kind + '-source.ts')).write_text('// Generated by scripts/reference_data.py; immutable content-addressed data.\nexport const ' + constant + ' = ' + repr('/data/' + name) + ';\n')
def emoji(rows):
    legacy = json.loads((ROOT / 'scripts/data/emoji-legacy-keywords.json').read_text())
    emit('emoji-data', {'version': '17.0', 'entries': rows, 'legacyKeywords': legacy})
    groups = list(dict.fromkeys(row['group'] for row in rows))
    (ROOT / 'web/src/emoji-catalog.ts').write_text('// Generated from Unicode Emoji 17.0; see scripts/data/unicode-17/LICENSE.txt.\nexport const EMOJI_VERSION = "17.0";\nexport interface CatalogEmoji { code: string; name: string; group: string; subgroup: string; version: string; asset: string; tones: readonly string[] }\nexport const EMOJI_GROUPS: readonly string[] = ' + json.dumps(groups, ensure_ascii=False) + ';\nexport const EMOJIS: readonly string[] = ' + json.dumps([r['code'] for r in rows], ensure_ascii=False, separators=(',', ':')) + ';\n')
